const REPLACEMENTS = [[/[–—]/g, "-"], [/→/g, ">"], [/[·•]/g, "-"], [/×/g, "X"], [/[‘’]/g, "'"]];

export function fontText(value) {
  let text = String(value).normalize("NFD").replace(/[\u0300-\u036f]/g, "");
  for (const [pattern, replacement] of REPLACEMENTS) text = text.replace(pattern, replacement);
  return [...text.toUpperCase()].map((char) => (GLYPHS[char] ? char : "?")).join("");
}

export function glyph(char) {
  return GLYPHS[char] ?? GLYPHS["?"];
}
